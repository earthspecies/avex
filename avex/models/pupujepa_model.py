"""PupuJEPA bioacoustic encoder — a 2D log-mel spectrogram I-JEPA.

PupuJEPA-Base (~86M) pretrained from scratch on pooled XenoCanto + iNaturalist +
AudioSet with a JEPA objective: a context encoder sees only visible patches and a
predictor regresses an EMA teacher's latents at masked positions. The deployed
feature extractor is the EMA teacher.

The vendored architecture in `avex/models/pupujepa/` is byte-identical to the
official PupuJEPA repo (github.com/sizigi/PupuJEPA), and the mel front-end below
reproduces its training code exactly — including the hardcoded normalisation
constants, which are baked into the weights and must not be changed.

SAMPLE RATE (deliberate, see AVEX paper §3.3)
  PupuJEPA is a 24 kHz model with fmax = 12 kHz. The paper evaluates all its own
  models at 16 kHz but runs Perch at 32 kHz and BirdNet at 48 kHz — "their
  proposed sample rates ... and to their advantage, they observe a broader
  frequency spectrogram". We follow that precedent and evaluate PupuJEPA at its
  native 24 kHz; a benchmark row for this model should carry the same footnote.

  Why the config asks for 32 kHz rather than 24 kHz: alp-data serves
  pre-resampled 32 kHz cheaply, but an un-cached rate triggers a whole-file
  kaiser_best resample costing seconds per clip (hours over CBI). We therefore
  request 32 kHz and resample the 10.24 s crop to 24 kHz here. 32 kHz Nyquist is
  16 kHz, well above fmax = 12 kHz, so nothing is lost — it is purely a speed
  path.

OUTPUT
  forward() returns (B, 1, 768): PupuJEPA's native clip embedding — mean over all
  patches within each 10.24 s window, then mean across windows. That is exactly
  the "time-averaged embeddings from the final layer" the paper's linear-probing
  protocol specifies (§3.4), so `aggregation: mean` over the length-1 axis is a
  no-op and the stored embedding is 2048x smaller than the raw patch grid.
"""

from __future__ import annotations

import json
import logging
import re
from pathlib import Path
from types import SimpleNamespace
from typing import Any, Dict, Optional

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
import torchaudio.functional as AF

from avex.models.base_model import ModelBase
from avex.models.pupujepa import PupuJEPA

logger = logging.getLogger(__name__)

# Global mel-normalisation constants PupuJEPA was trained with. Baked into the
# weights — do NOT change.
_PUPU_MEAN = -4.089994845986366
_PUPU_STD = 2.0242277159094813

_mel_basis: Dict[str, torch.Tensor] = {}
_hann_window: Dict[str, torch.Tensor] = {}

_DEFAULT_ARGS = Path(__file__).parent / "pupujepa" / "pupujepa_args.json"
_MEL_BASIS_FILE = Path(__file__).parent / "pupujepa" / "mel_basis_24k_n1024_m128_fmax12000.npy"


def _to_ns(obj: Any) -> Any:
    if isinstance(obj, dict):
        return SimpleNamespace(**{k: _to_ns(v) for k, v in obj.items()})
    if isinstance(obj, list):
        return [_to_ns(v) for v in obj]
    return obj


def load_pupu_config(path: str | Path) -> SimpleNamespace:
    """PupuJEPA's args.json is JSON5 (trailing commas). Strip them, then parse."""
    text = re.sub(r",(\s*[}\]])", r"\1", Path(path).read_text())
    return _to_ns(json.loads(text))


@torch.no_grad()
def extract_mel_features(y: torch.Tensor, cfg: SimpleNamespace) -> torch.Tensor:
    """(B, T_samples) -> (B, 1, T_frames, n_mels), verbatim PupuJEPA training mel."""
    dev = str(y.device)
    key = f"{cfg.preprocess.fmax}_{dev}"
    if key not in _mel_basis:
        # The filterbank is a fixed function of (sr, n_fft, n_mels, fmin, fmax),
        # so it is precomputed with librosa and vendored rather than adding a
        # librosa dependency to avex. Generated by exactly the call PupuJEPA
        # trains with:
        #   librosa.filters.mel(sr=24000, n_fft=1024, n_mels=128, fmin=0, fmax=12000)
        expected = _MEL_BASIS_FILE.name
        m = np.load(_MEL_BASIS_FILE)
        if m.shape != (cfg.preprocess.n_mels, cfg.preprocess.n_fft // 2 + 1):
            raise RuntimeError(
                f"vendored mel basis {expected} has shape {m.shape}, incompatible with "
                f"n_mels={cfg.preprocess.n_mels}, n_fft={cfg.preprocess.n_fft}"
            )
        _mel_basis[key] = torch.from_numpy(m).float().to(y.device)
        _hann_window[dev] = torch.hann_window(cfg.preprocess.win_size).to(y.device)

    pad = int((cfg.preprocess.n_fft - cfg.preprocess.hop_size) / 2)
    y = F.pad(y.unsqueeze(1), (pad, pad), mode="reflect").squeeze(1)
    spec = torch.stft(
        y,
        cfg.preprocess.n_fft,
        hop_length=cfg.preprocess.hop_size,
        win_length=cfg.preprocess.win_size,
        window=_hann_window[dev],
        center=False,
        pad_mode="reflect",
        normalized=False,
        onesided=True,
        return_complex=True,
    )
    spec = torch.view_as_real(spec)
    spec = torch.sqrt(spec.pow(2).sum(-1) + 1e-9)
    spec = torch.matmul(_mel_basis[key], spec)
    spec = torch.log(torch.clamp(spec, min=1e-5))
    if cfg.preprocess.normalize:
        spec = (spec - _PUPU_MEAN) / (_PUPU_STD + 1e-8)
    if cfg.preprocess.flip_ft:
        spec = spec.transpose(-2, -1)
    return spec.unsqueeze(1)


class PupuJEPAModel(ModelBase):
    """PupuJEPA EMA-teacher encoder exposed through the AVEX ModelBase interface.

    Parameters
    ----------
    device, audio_config
        Standard ModelBase arguments. `audio_config.sample_rate` is the rate the
        dataloader delivers (we request 32 kHz; see module docstring).
    num_classes, return_features_only
        A linear head is attached only when `return_features_only=False` and
        `num_classes > 0`; probing uses features only.
    extra_config
        `checkpoint_path` (required) — the PupuJEPA `model.safetensors`.
        `args_path` (optional) — that run's `args.json`; defaults to the vendored
        copy, which matches the released bigrun checkpoint.
    """

    def __init__(
        self,
        device: str = "cuda",
        audio_config: Optional[Any] = None,
        num_classes: int = 0,
        return_features_only: bool = False,   # matches eat_hf / beats_model; run_evaluate passes True explicitly
        extra_config: Optional[Dict[str, Any]] = None,
        pretrained: bool = True,
    ) -> None:
        super().__init__(device=device, audio_config=audio_config)

        extra_config = extra_config or {}
        ckpt = extra_config.get("checkpoint_path")
        if pretrained and not ckpt:
            raise ValueError(
                "PupuJEPAModel needs extra_config.checkpoint_path pointing at a "
                "PupuJEPA model.safetensors."
            )
        args_path = extra_config.get("args_path") or _DEFAULT_ARGS

        self.pupu_cfg = load_pupu_config(args_path)
        self.return_features_only = return_features_only

        # Opt-in switch for SUPERVISED POST-TRAINING of the backbone.
        #
        # This wrapper was written as an inference/embedding extractor: _embed_one
        # was decorated @torch.no_grad(), so NO gradient could ever reach the
        # backbone. Training with it would silently reduce to a linear probe --
        # loss falls, checkpoints save, and the backbone comes out bit-identical
        # to the SSL checkpoint. Verified: 0/399 backbone tensors received a
        # gradient even with requires_grad forced True on every parameter.
        #
        # The guard cannot key off self.training, because run_evaluate.py never
        # calls .eval() NOR wraps its embedding extraction in torch.no_grad() --
        # it relies entirely on that decorator. Keying off self.training would
        # therefore start building graphs during evaluation and blow up memory.
        # Hence an explicit flag, default False: eval behaviour is unchanged.
        self.trainable_backbone = bool(extra_config.get("trainable_backbone", False))

        backbone = PupuJEPA(self.pupu_cfg)
        if pretrained:
            from safetensors.torch import load_file

            sd = load_file(ckpt)
            missing, unexpected = backbone.load_state_dict(sd, strict=False)
            # Only patch_embed + teacher + rope_encoder are used at inference; the
            # student and predictor are training-only. Any gap in the deployed
            # path, however, would silently leave random weights in place.
            deployed_missing = [
                k for k in missing if k.startswith(("teacher.", "patch_embed.", "rope_encoder."))
            ]
            if deployed_missing:
                raise RuntimeError(
                    f"PupuJEPA checkpoint is missing deployed-path weights: {deployed_missing[:6]}"
                )
            logger.info(
                "Loaded PupuJEPA checkpoint %s (%d tensors; %d unused training-only keys)",
                ckpt,
                len(sd),
                len(missing),
            )

        self.backbone = backbone.to(self.device).eval()

        self.target_sr = self.pupu_cfg.preprocess.sample_rate            # 24000
        self.frame_len = (
            self.pupu_cfg.preprocess.cut_mel_frame * self.pupu_cfg.preprocess.hop_size
        )                                                                # 10.24 s
        self.input_sr = int(getattr(audio_config, "sample_rate", self.target_sr) or self.target_sr)

        # Identity marker so a forward hook on the "last layer" captures exactly
        # the same tensor forward() returns, whichever path AVEX's probe takes.
        self.output_features = nn.Identity()

        self.classifier: Optional[nn.Module] = None
        if not return_features_only and num_classes > 0:
            self.classifier = nn.Linear(self.pupu_cfg.model.embed_dim, num_classes).to(self.device)

    # -- AVEX layer discovery ------------------------------------------------
    def _discover_embedding_layers(self) -> None:
        """Expose a single embedding layer: the pooled final-layer output.

        The paper's probing protocol uses time-averaged final-layer embeddings,
        so that is the only tensor worth exposing. Registering the Identity marker
        (rather than a transformer block) also guarantees a hook and the forward
        return value agree.
        """
        if len(self._layer_names) == 0:
            self._layer_names = ["output_features"]

    # -- audio -> windows ----------------------------------------------------
    def _windows(self, audio: torch.Tensor) -> torch.Tensor:
        """(T,) -> (n_windows, frame_len): all non-overlapping 10.24 s windows."""
        length = audio.shape[-1]
        if length <= self.frame_len:
            return F.pad(audio, (0, self.frame_len - length)).unsqueeze(0)
        n = length // self.frame_len
        chunks = [audio[c * self.frame_len : (c + 1) * self.frame_len] for c in range(n)]
        rem = audio[n * self.frame_len :]
        if rem.shape[-1] > self.frame_len // 4:      # keep a substantial tail
            chunks.append(F.pad(rem, (0, self.frame_len - rem.shape[-1])))
        return torch.stack(chunks)

    def _embed_one(self, audio: torch.Tensor) -> torch.Tensor:
        """(T,) waveform at input_sr -> (D,) pooled embedding.

        Grad is enabled ONLY when post-training the backbone (see
        self.trainable_backbone). Otherwise this stays under no_grad exactly as
        the original @torch.no_grad() decorator had it.
        """
        with torch.set_grad_enabled(self.trainable_backbone and torch.is_grad_enabled()):
            return self._embed_one_impl(audio)

    def _embed_one_impl(self, audio: torch.Tensor) -> torch.Tensor:
        """Body of _embed_one; grad context is set by the caller."""
        if self.input_sr != self.target_sr:
            audio = AF.resample(audio, self.input_sr, self.target_sr)
        windows = self._windows(audio).to(self.device)               # (C, frame_len)
        mel = extract_mel_features(windows, self.pupu_cfg)           # (C, 1, 1024, 128)
        x_all = self.backbone.patch_embed(mel)                       # (C, P, D)
        grid = self.backbone.get_dynamic_grid_size(mel)
        rope_full = self.backbone.rope_encoder.get_embed(grid)       # (P, rope_dim)
        C, P = x_all.shape[0], x_all.shape[1]
        idx = torch.arange(P, device=self.device).unsqueeze(0).expand(C, P)
        rope_sel = rope_full[idx].unsqueeze(1)                       # (C, 1, P, rope_dim)
        h = self.backbone.teacher(x_all, rope=rope_sel)              # (C, P, D)
        # Mean over patches within a window, then across windows — PupuJEPA's
        # native clip embedding.
        return h.mean(dim=1).mean(dim=0)

    # -- forward -------------------------------------------------------------
    def forward(
        self,
        x: torch.Tensor,
        padding_mask: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        """x: (B, T) raw waveform at input_sr. Returns (B, 1, D) features.

        Clips are processed one at a time because each may tile into a different
        number of 10.24 s windows; batching happens at the window level inside
        `_embed_one`.
        """
        if x.dim() == 1:
            x = x.unsqueeze(0)
        if x.dim() == 3:                       # (B, 1, T) or (B, C, T) -> mono
            x = x.mean(dim=1)

        feats = torch.stack([self._embed_one(x[i].float()) for i in range(x.shape[0])])
        feats = self.output_features(feats.unsqueeze(1))          # (B, 1, D)

        if self.return_features_only or self.classifier is None:
            return feats
        return self.classifier(feats.mean(dim=1))
